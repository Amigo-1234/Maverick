// Bundles db/migrations/*.sql into lib/server/migrations.generated.ts so the app can apply them
// without reading loose files at runtime. Runs automatically before `npm run build` and `npm run dev`.
import fs from "node:fs";
const dir = "db/migrations";
const files = fs.readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(`${dir}/${f}`, "utf8"))} },`).join("\n");
fs.writeFileSync("lib/server/migrations.generated.ts", `// GENERATED by scripts/bundle-migrations.mjs from db/migrations/*.sql. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log(`bundled ${files.length} migrations`);
