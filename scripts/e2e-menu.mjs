// Navbar menu test in installed Chrome. Usage: node scripts/e2e-menu.mjs [baseUrl]
import { chromium } from "playwright-core";
const base = process.argv[2] ?? "http://localhost:3123";
const shots = process.env.SHOTS ?? ".";
const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; p.on("pageerror", (e) => errors.push(e.message)); p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const ok = (c, m) => { console.log(`${c ? "PASS" : "FAIL"}  ${m}`); if (!c) process.exitCode = 1; };
await p.goto(base + "/"); await p.waitForLoadState("networkidle");
const btn = p.locator(".nav-close-btn");
ok(!(await p.locator(".nav-overlay-wrapper").isVisible()), "menu starts closed");
const peek = await p.evaluate(() => {
  const box = document.querySelector(".menu-button-text").getBoundingClientRect();
  const close = document.querySelectorAll(".menu-button-text p")[1].getBoundingClientRect();
  return close.top >= box.bottom - 0.5;
});
ok(peek, "closed button shows only MENU (CLOSE is fully hidden)");
await btn.click();
await p.waitForTimeout(250); await p.screenshot({ path: `${shots}/menu-mid.png` });
await p.waitForTimeout(1300);
ok(await p.locator(".nav-overlay-wrapper").isVisible(), "menu opens");
ok((await btn.getAttribute("aria-expanded")) === "true", "button reports expanded");
ok(await p.evaluate(() => document.activeElement?.classList.contains("nav-link")), "focus moves to the first link");
ok(await p.evaluate(() => getComputedStyle(document.body).overflow === "hidden"), "page behind can't scroll");
await p.locator(".menu-list-item").nth(3).hover(); await p.waitForTimeout(800);
ok(await p.locator(".bg-shape-4.active").count() === 1, "hovering Ringers shows its ring shape");
await p.screenshot({ path: `${shots}/menu-open.png` });
await p.keyboard.press("Escape"); await p.waitForTimeout(1200);
ok(!(await p.locator(".nav-overlay-wrapper").isVisible()), "Escape closes the menu");
ok(await p.evaluate(() => document.activeElement?.classList.contains("nav-close-btn")), "focus returns to the Menu button");
await btn.click(); await p.waitForTimeout(1300);
await p.getByRole("link", { name: /Ringers/ }).first().click();
await p.waitForURL("**/collections/ringers"); await p.waitForTimeout(1200);
ok(!(await p.locator(".nav-overlay-wrapper").isVisible()), "menu link navigates to Ringers and the menu closes");
await btn.click(); await p.waitForTimeout(1300);
await p.mouse.click(100, 500); await p.waitForTimeout(1200);
ok(!(await p.locator(".nav-overlay-wrapper").isVisible()), "clicking the dark overlay closes the menu");
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto(base + "/"); await m.waitForLoadState("networkidle");
await m.locator(".nav-close-btn").click(); await m.waitForTimeout(1500);
ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, "no sideways scroll on phone with menu open");
await m.screenshot({ path: `${shots}/menu-phone.png` });
const r = await b.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
await r.goto(base + "/"); await r.waitForLoadState("networkidle");
await r.locator(".nav-close-btn").click(); await r.waitForTimeout(150);
ok(await r.locator(".nav-link").first().isVisible(), "reduced motion: menu appears instantly");
ok(errors.length === 0, `no console errors${errors.length ? ": " + errors.slice(0, 2).join(" | ") : ""}`);
await b.close();
